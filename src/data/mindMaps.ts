const LESSON_INDEX: Record<string, MindMapLesson> = Object.fromEntries(
  MIND_MAP_UNITS.flatMap((u) => u.lessons.map((l) => [l.id, l] as const))
);

const UNIT_OF_LESSON: Record<string, MindMapUnit> = Object.fromEntries(
  MIND_MAP_UNITS.flatMap((u) => u.lessons.map((l) => [l.id, u] as const))
);

/** خريطة درس واحد، أو undefined إن لم توجد */
export const getLessonMindMap = (lessonId: string): MindMapLesson | undefined =>
  LESSON_INDEX[lessonId];

/** الوحدة التي ينتمي إليها الدرس */
export const getUnitOfLesson = (lessonId: string): MindMapUnit | undefined =>
  UNIT_OF_LESSON[lessonId];

/** خريطة وحدة كاملة بالرقم (1..10) */
export const getUnitMindMap = (unitNumber: number): MindMapUnit | undefined =>
  MIND_MAP_UNITS.find((u) => u.n === unitNumber);

/** يقبل 'unit-7' أو '7' أو 7 */
export const getUnitMindMapBySlug = (slug: string | number): MindMapUnit | undefined => {
  const n = typeof slug === 'number' ? slug : Number(String(slug).replace(/\D+/g, ''));
  return Number.isFinite(n) ? getUnitMindMap(n) : undefined;
};

export const MIND_MAP_LESSON_COUNT = Object.keys(LESSON_INDEX).length;
